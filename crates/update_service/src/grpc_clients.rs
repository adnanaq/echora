impl CatalogueDataPort for GrpcCatalogueAdapter {
    fn list_entity_pages(
        &self,
        entity_kind: RefreshEntityKind,
        entity_id: String,
    ) -> BoxFuture<'_, Result<ListEntityPagesOutput, PortError>> {
        let mut postgres = self.postgres.clone();
        Box::pin(async move {
            let response = postgres
                .list_entity_pages(ListEntityPagesRequest {
                    entity_type: to_proto_entity_type(entity_kind),
                    entity_id,
                })
                .await
                .map_err(|status| map_grpc_status(&status))?
                .into_inner();

            let pages = response
                .pages
                .into_iter()
                .filter_map(|page| {
                    page.page_key.map(|key| EntityPageSummary {
                        page_key: from_proto_page_key(key),
                        is_partial_source: page.is_partial_source,
                        fetched_at_epoch_seconds: page.fetched_at.map(|ts| ts.seconds),
                        is_dead: page.is_dead,
                        fetch_failed_at_epoch_seconds: page.fetch_failed_at.map(|ts| ts.seconds),
                        fetch_failures: page.fetch_failures,
                    })
                })
                .collect();

            Ok(ListEntityPagesOutput {
                pages,
                entity_merge_version: None,
            })
        })
    }

    fn refresh_page(
        &self,
        page_key: RefreshPageKey,
        max_age_seconds: i64,
    ) -> BoxFuture<'_, Result<RefreshPageOutput, PortError>> {
        let mut enrichment = self.fetch_enrichment.clone();
        let mut postgres = self.postgres.clone();
        Box::pin(async move {
            let proto_key = to_proto_page_key(&page_key);
            let fetch_res = enrichment
                .fetch_page(FetchPageRequest {
                    page_key: Some(proto_key.clone()),
                    max_age: Some(prost_types::Duration {
                        seconds: max_age_seconds.max(0),
                        nanos: 0,
                    }),
                })
                .await;

            match fetch_res {
                Ok(resp) => {
                    let stored_page = resp.into_inner().page.ok_or_else(|| {
                        PortError::non_retryable("FetchPage response missing page")
                    })?;
                    let has_failed = stored_page.responses.is_empty() && !stored_page.is_not_found;
                    let store_resp = postgres
                        .store_page(StorePageRequest {
                            page: Some(stored_page),
                        })
                        .await
                        .map_err(|status| map_grpc_status(&status))?
                        .into_inner();
                    Ok(RefreshPageOutput {
                        page_key,
                        has_changed: store_resp.has_changed,
                        has_failed,
                    })
                }
                Err(status) => {
                    // Record page failure via StorePage so backoff applies and refresh continues.
                    let now = Utc::now();
                    let _ = postgres
                        .store_page(StorePageRequest {
                            page: Some(StoredPage {
                                page_key: Some(proto_key),
                                fetched_at: Some(prost_types::Timestamp {
                                    seconds: now.timestamp(),
                                    nanos: 0,
                                }),
                                is_not_found: false,
                                is_dead: false,
                                responses: Vec::new(),
                            }),
                        })
                        .await;
                    let _ = status;
                    Ok(RefreshPageOutput {
                        page_key,
                        has_changed: false,
                        has_failed: true,
                    })
                }
            }
        })
    }

    fn merge_entity_attempt(
        &self,
        entity_kind: RefreshEntityKind,
        entity_id: String,
        merge_version: i32,
    ) -> BoxFuture<'_, Result<MergeAttemptOutcome, PortError>> {
        let postgres = self.postgres.clone();
        let enrichment = self.merge_enrichment.clone();
        Box::pin(async move {
            match entity_kind {
                RefreshEntityKind::Anime => {
                    merge_anime_rpc(postgres, enrichment, entity_id, merge_version).await
                }
                RefreshEntityKind::Episode => {
                    merge_episode_rpc(postgres, enrichment, entity_id, merge_version).await
                }
                RefreshEntityKind::Character => {
                    merge_character_rpc(postgres, enrichment, entity_id, merge_version).await
                }
            }
        })
    }

    fn record_refresh(&self, input: RecordRefreshInput) -> BoxFuture<'_, Result<(), PortError>> {
        let mut postgres = self.postgres.clone();
        Box::pin(async move {
            let outcome = match input.outcome {
                RefreshOutcomeKind::Succeeded => ProtoRefreshOutcome::Succeeded as i32,
                RefreshOutcomeKind::PagesFailed => ProtoRefreshOutcome::PagesFailed as i32,
                RefreshOutcomeKind::Failed => ProtoRefreshOutcome::Failed as i32,
            };
            postgres
                .record_refresh(RecordRefreshRequest {
                    entity_type: to_proto_entity_type(input.entity_kind),
                    entity_id: input.entity_id,
                    outcome,
                    refresh_after: Some(prost_types::Duration {
                        seconds: input.refresh_after_days.max(1) * 86_400,
                        nanos: 0,
                    }),
                })
                .await
                .map_err(|status| map_grpc_status(&status))?;
            Ok(())
        })
    }
}

/// Top-level Temporal workflow starter using `USE_EXISTING` and inherited `RefreshTrigger`.
#[derive(Clone)]
pub struct TemporalWorkflowStarter {
    client: Client,
}

impl TemporalWorkflowStarter {
    /// Creates a starter backed by a connected Temporal `client`.
    #[must_use]
    pub fn new(client: Client) -> Self {
        Self { client }
    }
}

#[derive(Serialize)]
struct ChildRefreshStartInput {
    entity_id: String,
    trigger: String,
    priority: u32,
}

/// Encodes a serializable workflow input into a Temporal JSON [`RawValue`].
fn encode_json_raw_value<T: Serialize>(value: &T) -> Result<RawValue, PortError> {
    let bytes = serde_json::to_vec(value)
        .map_err(|err| PortError::non_retryable(format!("failed to serialize input: {err}")))?;
    let mut metadata = std::collections::HashMap::new();
    metadata.insert("encoding".to_owned(), b"json/plain".to_vec());
    Ok(RawValue {
        payloads: vec![Payload {
            metadata,
            data: bytes,
            ..Payload::default()
        }],
    })
}

/// Builds `WorkflowStartOptions` with `USE_EXISTING`, priority, and `RefreshTrigger`.
fn build_start_options(
    task_queue: &str,
    workflow_id: String,
    priority: Priority,
    search_attrs: SearchAttributes,
) -> WorkflowStartOptions {
    WorkflowStartOptions::new(task_queue, workflow_id)
        .id_conflict_policy(WorkflowIdConflictPolicy::UseExisting)
        .priority(priority)
        .search_attributes(search_attrs)
        .build()
}

/// Starts one untyped top-level Temporal workflow with `USE_EXISTING`, priority, and `RefreshTrigger`.
async fn start_untyped_workflow(
    client: &Client,
    task_queue: &str,
    workflow_type: &str,
    workflow_id: String,
    priority: Priority,
    search_attrs: SearchAttributes,
    input: &ChildRefreshStartInput,
) -> Result<(), PortError> {
    let opts = build_start_options(task_queue, workflow_id, priority, search_attrs);
    let raw_input = encode_json_raw_value(input)?;
    client
        .start_workflow(UntypedWorkflow::new(workflow_type), raw_input, opts)
        .await
        .map_err(|err| PortError::retryable(err.to_string()))?;
    Ok(())
}

/// Starts top-level `RefreshEpisodeWorkflow` or `RefreshCharacterWorkflow` instances
/// with `USE_EXISTING` conflict policy.
async fn start_entity_refresh_batch(
    client: &Client,
    kind: RefreshEntityKind,
    entity_ids: Vec<String>,
    trigger: &str,
    raw_priority: u32,
    priority: &Priority,
    search_attrs: &SearchAttributes,
) -> Result<usize, PortError> {
    let mut started = 0_usize;
    for entity_id in entity_ids {
        let wf_input = RefreshEntityInput {
            entity_id: entity_id.clone(),
            trigger: trigger.to_owned(),
            priority: raw_priority,
            ..RefreshEntityInput::default()
        };
        let wf_id = match kind {
            RefreshEntityKind::Episode => build_refresh_episode_workflow_id(&entity_id),
            RefreshEntityKind::Character => build_refresh_character_workflow_id(&entity_id),
            RefreshEntityKind::Anime => continue,
        };
        let opts = build_start_options(
            UPDATE_SERVICE_TASK_QUEUE,
            wf_id,
            priority.clone(),
            search_attrs.clone(),
        );
        match kind {
            RefreshEntityKind::Episode => {
                client
                    .start_workflow(RefreshEpisodeWorkflow::run, wf_input, opts)
                    .await
                    .map_err(|err| PortError::retryable(err.to_string()))?;
            }
            RefreshEntityKind::Character => {
                client
                    .start_workflow(RefreshCharacterWorkflow::run, wf_input, opts)
                    .await
                    .map_err(|err| PortError::retryable(err.to_string()))?;
            }
            RefreshEntityKind::Anime => {}
        }
        started += 1;
    }
    Ok(started)
}

impl WorkflowStarterPort for TemporalWorkflowStarter {
    fn start_entity_workflows(
        &self,
        input: StartEntityWorkflowsInput,
    ) -> BoxFuture<'_, Result<usize, PortError>> {
        let client = self.client.clone();
        Box::pin(async move {
            let trigger_val = if input.trigger.is_empty() {
                "sweep".to_owned()
            } else {
                input.trigger.clone()
            };

            let priority = build_priority(input.priority, &trigger_val);
            let trigger_key = SearchAttributeKey::keyword(REFRESH_TRIGGER_SEARCH_ATTRIBUTE);
            let search_attrs = SearchAttributes::new([trigger_key.value_set(trigger_val.clone())]);

            let mut started = start_entity_refresh_batch(
                &client,
                RefreshEntityKind::Episode,
                input.episode_ids,
                &trigger_val,
                input.priority,
                &priority,
                &search_attrs,
            )
            .await?;

            started += start_entity_refresh_batch(
                &client,
                RefreshEntityKind::Character,
                input.character_ids,
                &trigger_val,
                input.priority,
                &priority,
                &search_attrs,
            )
            .await?;

            for target in input.character_fetch_requests {
                let wf_id = build_refresh_character_workflow_id(&target.character_id);
                let opts = build_start_options(
                    UPDATE_SERVICE_TASK_QUEUE,
                    wf_id,
                    priority.clone(),
                    search_attrs.clone(),
                );
                client
                    .signal_with_start_workflow(
                        RefreshCharacterWorkflow::run,
                        RefreshEntityInput {
                            entity_id: target.character_id,
                            trigger: trigger_val.clone(),
                            priority: input.priority,
                            ..RefreshEntityInput::default()
                        },
                        RefreshCharacterWorkflow::fetch_requested,
                        target.fetch,
                        opts,
                    )
                    .await
                    .map_err(|err| PortError::retryable(err.to_string()))?;
                started += 1;
            }

            if input.start_synopsis {
                let wf_id = build_write_synopsis_workflow_id(&input.anime_id);
                let child_input = ChildRefreshStartInput {
                    entity_id: input.anime_id,
                    trigger: trigger_val,
                    priority: input.priority,
                };
                start_untyped_workflow(
                    &client,
                    AGENT_SERVICE_TASK_QUEUE,
                    "WriteSynopsisWorkflow",
                    wf_id,
                    priority,
                    search_attrs,
                    &child_input,
                )
                .await?;
                started += 1;
            }

            Ok(started)
        })
    }
}
