/// Maximum gRPC message size (64 MiB) configured on Update Service clients.
pub const MAX_GRPC_MESSAGE_BYTES: usize = 64 * 1024 * 1024;

/// Builds a `PostgresServiceClient` configured with gzip compression and 64 MiB limits.
///
/// # Examples
///
/// ```no_run
/// # use tonic::transport::Channel;
/// # async fn example() -> Result<(), tonic::transport::Error> {
/// let channel = Channel::from_static("http://localhost:8004").connect_lazy();
/// let _client = update_service::build_postgres_client(channel);
/// # Ok(())
/// # }
/// ```
#[must_use]
pub fn build_postgres_client(channel: Channel) -> PostgresServiceClient<Channel> {
    PostgresServiceClient::new(channel)
        .send_compressed(CompressionEncoding::Gzip)
        .accept_compressed(CompressionEncoding::Gzip)
        .max_decoding_message_size(MAX_GRPC_MESSAGE_BYTES)
        .max_encoding_message_size(MAX_GRPC_MESSAGE_BYTES)
}

/// Builds an `EnrichmentServiceClient` configured with gzip compression and 64 MiB limits.
///
/// # Examples
///
/// ```no_run
/// # use tonic::transport::Channel;
/// # async fn example() -> Result<(), tonic::transport::Error> {
/// let channel = Channel::from_static("http://localhost:8002").connect_lazy();
/// let _client = update_service::build_enrichment_client(channel);
/// # Ok(())
/// # }
/// ```
#[must_use]
pub fn build_enrichment_client(channel: Channel) -> EnrichmentServiceClient<Channel> {
    EnrichmentServiceClient::new(channel)
        .send_compressed(CompressionEncoding::Gzip)
        .accept_compressed(CompressionEncoding::Gzip)
        .max_decoding_message_size(MAX_GRPC_MESSAGE_BYTES)
        .max_encoding_message_size(MAX_GRPC_MESSAGE_BYTES)
}

/// Maps a `tonic::Status` into a [`PortError`], marking permanent codes non-retryable.
///
/// # Examples
///
/// ```
/// use temporal_workflows::PortErrorKind;
/// use tonic::Status;
/// use update_service::map_grpc_status;
///
/// assert_eq!(map_grpc_status(&Status::not_found("missing")).kind, PortErrorKind::NonRetryable);
/// assert_eq!(map_grpc_status(&Status::unavailable("busy")).kind, PortErrorKind::Retryable);
/// ```
#[must_use]
pub fn map_grpc_status(status: &tonic::Status) -> PortError {
    if is_non_retryable_grpc_code(status.code() as i32) {
        PortError::non_retryable(status.to_string())
    } else {
        PortError::retryable(status.to_string())
    }
}

/// gRPC-backed implementation of [`CatalogueDataPort`] talking to `postgres_service` and
/// `enrichment_service` (supporting either one shared client or split fetch/merge endpoints).
#[derive(Clone)]
pub struct GrpcCatalogueAdapter {
    postgres: PostgresServiceClient<Channel>,
    fetch_enrichment: EnrichmentServiceClient<Channel>,
    merge_enrichment: EnrichmentServiceClient<Channel>,
}

impl GrpcCatalogueAdapter {
    /// Creates an adapter using one shared `enrichment` client for both fetches and merges.
    #[must_use]
    pub fn new(
        postgres: PostgresServiceClient<Channel>,
        enrichment: EnrichmentServiceClient<Channel>,
    ) -> Self {
        Self::with_split_enrichment(postgres, enrichment.clone(), enrichment)
    }

    /// Creates an adapter with independent `fetch_enrichment` and `merge_enrichment` clients.
    #[must_use]
    pub fn with_split_enrichment(
        postgres: PostgresServiceClient<Channel>,
        fetch_enrichment: EnrichmentServiceClient<Channel>,
        merge_enrichment: EnrichmentServiceClient<Channel>,
    ) -> Self {
        Self {
            postgres,
            fetch_enrichment,
            merge_enrichment,
        }
    }
}

/// Converts a [`RefreshPageKey`] into a proto `PageKey`.
fn to_proto_page_key(key: &RefreshPageKey) -> ProtoPageKey {
    let entity_type = match key.entity_type.as_str() {
        "anime" => ProtoEntityType::Anime as i32,
        "character" => ProtoEntityType::Character as i32,
        "episode" => ProtoEntityType::Episode as i32,
        _ => ProtoEntityType::Unspecified as i32,
    };
    ProtoPageKey {
        provider: key.provider.clone(),
        entity_type,
        address: key.address.clone(),
    }
}

/// Converts a proto `PageKey` into a [`RefreshPageKey`].
fn from_proto_page_key(key: ProtoPageKey) -> RefreshPageKey {
    let entity_type = match ProtoEntityType::try_from(key.entity_type) {
        Ok(ProtoEntityType::Anime) => "anime",
        Ok(ProtoEntityType::Character) => "character",
        Ok(ProtoEntityType::Episode) => "episode",
        _ => "unspecified",
    };
    RefreshPageKey {
        provider: key.provider,
        entity_type: entity_type.to_owned(),
        address: key.address,
    }
}

/// Converts a [`RefreshEntityKind`] into a proto `EntityType`.
const fn to_proto_entity_type(kind: RefreshEntityKind) -> i32 {
    match kind {
        RefreshEntityKind::Anime => ProtoEntityType::Anime as i32,
        RefreshEntityKind::Episode => ProtoEntityType::Episode as i32,
        RefreshEntityKind::Character => ProtoEntityType::Character as i32,
    }
}

/// Converts a gRPC `Save*` response/status into [`MergeAttemptOutcome`].
fn map_save_result<T, F>(
    save_res: Result<tonic::Response<T>, tonic::Status>,
    map_saved: F,
) -> Result<MergeAttemptOutcome, PortError>
where
    F: FnOnce(T) -> MergeEntityOutput,
{
    match save_res {
        Ok(resp) => Ok(MergeAttemptOutcome::Saved(map_saved(resp.into_inner()))),
        Err(status) if status.code() == tonic::Code::Aborted => {
            Ok(MergeAttemptOutcome::VersionConflict(status.to_string()))
        }
        Err(status) => Err(map_grpc_status(&status)),
    }
}

/// Executes `LoadAnime` -> `MergeAnime` -> `SaveAnime`.
async fn merge_anime_rpc(
    mut postgres: PostgresServiceClient<Channel>,
    mut enrichment: EnrichmentServiceClient<Channel>,
    anime_id: String,
    merge_version: i32,
) -> Result<MergeAttemptOutcome, PortError> {
    let loaded = postgres
        .load_anime(LoadAnimeRequest {
            anime_id: anime_id.clone(),
        })
        .await
        .map_err(|status| map_grpc_status(&status))?
        .into_inner();

    let merged = enrichment
        .merge_anime(MergeAnimeRequest {
            anime_id: anime_id.clone(),
            source_pages: loaded.source_pages,
            partial_source_pages: loaded.partial_source_pages,
            corrections: loaded.corrections,
            generated_texts: Vec::new(),
            known_episodes: loaded.known_episodes,
        })
        .await
        .map_err(|status| map_grpc_status(&status))?
        .into_inner();

    let synopses_changed = !merged.provider_synopses_hash.is_empty();
    let save_res = postgres
        .save_anime(SaveAnimeRequest {
            anime_id,
            expected_version: loaded.version,
            anime: merged.anime,
            merge_version,
            relation_claims: merged.relation_claims,
            episodes: merged.episodes,
        })
        .await;

    map_save_result(save_res, |saved| {
        let mut changed_episode_ids = saved.created_episode_ids;
        changed_episode_ids.extend(saved.updated_episode_ids);
        MergeEntityOutput {
            has_changed: saved.has_changed,
            changed_episode_ids,
            has_changed_synopses: synopses_changed,
        }
    })
}

/// Executes `LoadEpisode` -> `MergeEpisode` -> `SaveEpisode`.
async fn merge_episode_rpc(
    mut postgres: PostgresServiceClient<Channel>,
    mut enrichment: EnrichmentServiceClient<Channel>,
    episode_id: String,
    merge_version: i32,
) -> Result<MergeAttemptOutcome, PortError> {
    let loaded = postgres
        .load_episode(LoadEpisodeRequest {
            episode_id: episode_id.clone(),
        })
        .await
        .map_err(|status| map_grpc_status(&status))?
        .into_inner();

    let merged = enrichment
        .merge_episode(MergeEpisodeRequest {
            episode_id: episode_id.clone(),
            anime_id: loaded.anime_id,
            pages: loaded.pages,
            corrections: loaded.corrections,
            list_entries: loaded.list_entries,
        })
        .await
        .map_err(|status| map_grpc_status(&status))?
        .into_inner();

    let save_res = postgres
        .save_episode(SaveEpisodeRequest {
            episode_id,
            expected_version: loaded.version,
            episode: merged.episode,
            merge_version,
        })
        .await;

    map_save_result(save_res, |saved| MergeEntityOutput {
        has_changed: saved.has_changed,
        changed_episode_ids: Vec::new(),
        has_changed_synopses: false,
    })
}

