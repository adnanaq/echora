/// Maximum gRPC message size (64 MiB) configured on Update Service clients.
pub const MAX_GRPC_MESSAGE_BYTES: usize = 64 * 1024 * 1024;

/// Builds a `PostgresServiceClient` configured with gzip compression and 64 MiB limits.
///
/// # Examples
///
/// ```no_run
/// # use tonic::transport::Channel;
/// # async fn example() -> Result<(), tonic::transport::Error> {
/// let channel = Channel::from_static("http://localhost:8004").connect_lazy();
/// let _client = update_service::build_postgres_client(channel);
/// # Ok(())
/// # }
/// ```
#[must_use]
pub fn build_postgres_client(channel: Channel) -> PostgresServiceClient<Channel> {
    PostgresServiceClient::new(channel)
        .send_compressed(CompressionEncoding::Gzip)
        .accept_compressed(CompressionEncoding::Gzip)
        .max_decoding_message_size(MAX_GRPC_MESSAGE_BYTES)
        .max_encoding_message_size(MAX_GRPC_MESSAGE_BYTES)
}

/// Builds an `EnrichmentServiceClient` configured with gzip compression and 64 MiB limits.
///
/// # Examples
///
/// ```no_run
/// # use tonic::transport::Channel;
/// # async fn example() -> Result<(), tonic::transport::Error> {
/// let channel = Channel::from_static("http://localhost:8002").connect_lazy();
/// let _client = update_service::build_enrichment_client(channel);
/// # Ok(())
/// # }
/// ```
#[must_use]
pub fn build_enrichment_client(channel: Channel) -> EnrichmentServiceClient<Channel> {
    EnrichmentServiceClient::new(channel)
        .send_compressed(CompressionEncoding::Gzip)
        .accept_compressed(CompressionEncoding::Gzip)
        .max_decoding_message_size(MAX_GRPC_MESSAGE_BYTES)
        .max_encoding_message_size(MAX_GRPC_MESSAGE_BYTES)
}

/// Maps a `tonic::Status` into a [`PortError`], marking permanent codes non-retryable.
#[must_use]
pub fn map_grpc_status(status: &tonic::Status) -> PortError {
    if is_non_retryable_grpc_code(status.code() as i32) {
        PortError::non_retryable(status.to_string())
    } else {
        PortError::retryable(status.to_string())
    }
}

/// gRPC-backed implementation of [`CatalogueDataPort`] talking to `postgres_service` and
/// `enrichment_service`.
#[derive(Clone)]
pub struct GrpcCatalogueAdapter {
    postgres: PostgresServiceClient<Channel>,
    enrichment: EnrichmentServiceClient<Channel>,
}

impl GrpcCatalogueAdapter {
    /// Creates an adapter from pre-configured `postgres` and `enrichment` gRPC clients.
    #[must_use]
    pub fn new(
        postgres: PostgresServiceClient<Channel>,
        enrichment: EnrichmentServiceClient<Channel>,
    ) -> Self {
        Self {
            postgres,
            enrichment,
        }
    }
}

/// Converts a [`RefreshPageKey`] into a proto `PageKey`.
fn to_proto_page_key(key: &RefreshPageKey) -> ProtoPageKey {
    let entity_type = match key.entity_type.as_str() {
        "anime" => ProtoEntityType::Anime as i32,
        "character" => ProtoEntityType::Character as i32,
        "episode" => ProtoEntityType::Episode as i32,
        _ => ProtoEntityType::Unspecified as i32,
    };
    ProtoPageKey {
        provider: key.provider.clone(),
        entity_type,
        address: key.address.clone(),
    }
}

/// Converts a proto `PageKey` into a [`RefreshPageKey`].
fn from_proto_page_key(key: ProtoPageKey) -> RefreshPageKey {
    let entity_type = match ProtoEntityType::try_from(key.entity_type) {
        Ok(ProtoEntityType::Anime) => "anime",
        Ok(ProtoEntityType::Character) => "character",
        Ok(ProtoEntityType::Episode) => "episode",
        _ => "unspecified",
    };
    RefreshPageKey {
        provider: key.provider,
        entity_type: entity_type.to_owned(),
        address: key.address,
    }
}

impl CatalogueDataPort for GrpcCatalogueAdapter {
    fn list_entity_pages(
        &self,
        anime_id: String,
    ) -> BoxFuture<'_, Result<ListEntityPagesOutput, PortError>> {
        let mut postgres = self.postgres.clone();
        Box::pin(async move {
            let response = postgres
                .list_entity_pages(ListEntityPagesRequest {
                    entity_type: ProtoEntityType::Anime as i32,
                    entity_id: anime_id,
                })
                .await
                .map_err(|status| map_grpc_status(&status))?
                .into_inner();

            let pages = response
                .pages
                .into_iter()
                .filter_map(|page| {
                    page.page_key.map(|key| EntityPageSummary {
                        page_key: from_proto_page_key(key),
                        is_partial_source: page.is_partial_source,
                        fetched_at_epoch_seconds: page.fetched_at.map(|ts| ts.seconds),
                        is_dead: page.is_dead,
                        fetch_failed_at_epoch_seconds: page.fetch_failed_at.map(|ts| ts.seconds),
                        fetch_failures: page.fetch_failures,
                    })
                })
                .collect();

            Ok(ListEntityPagesOutput {
                pages,
                entity_merge_version: None,
            })
        })
    }

    fn refresh_page(
        &self,
        page_key: RefreshPageKey,
        max_age_seconds: i64,
    ) -> BoxFuture<'_, Result<RefreshPageOutput, PortError>> {
        let mut enrichment = self.enrichment.clone();
        let mut postgres = self.postgres.clone();
        Box::pin(async move {
            let proto_key = to_proto_page_key(&page_key);
            let fetch_res = enrichment
                .fetch_page(FetchPageRequest {
                    page_key: Some(proto_key.clone()),
                    max_age: Some(prost_types::Duration {
                        seconds: max_age_seconds.max(0),
                        nanos: 0,
                    }),
                })
                .await;

            match fetch_res {
                Ok(resp) => {
                    let stored_page = resp.into_inner().page.ok_or_else(|| {
                        PortError::non_retryable("FetchPage response missing page")
                    })?;
                    let has_failed = stored_page.responses.is_empty() && !stored_page.is_not_found;
                    let store_resp = postgres
                        .store_page(StorePageRequest {
                            page: Some(stored_page),
                        })
                        .await
                        .map_err(|status| map_grpc_status(&status))?
                        .into_inner();
                    Ok(RefreshPageOutput {
                        page_key,
                        has_changed: store_resp.has_changed,
                        has_failed,
                    })
                }
                Err(status) => {
                    // Record page failure via StorePage so backoff applies and refresh continues.
                    let now = Utc::now();
                    let _ = postgres
                        .store_page(StorePageRequest {
                            page: Some(StoredPage {
                                page_key: Some(proto_key),
                                fetched_at: Some(prost_types::Timestamp {
                                    seconds: now.timestamp(),
                                    nanos: 0,
                                }),
                                is_not_found: false,
                                is_dead: false,
                                responses: Vec::new(),
                            }),
                        })
                        .await;
                    let _ = status;
                    Ok(RefreshPageOutput {
                        page_key,
                        has_changed: false,
                        has_failed: true,
                    })
                }
            }
        })
    }

    fn merge_anime_attempt(
        &self,
        anime_id: String,
        merge_version: i32,
    ) -> BoxFuture<'_, Result<MergeAttemptOutcome, PortError>> {
        let mut postgres = self.postgres.clone();
        let mut enrichment = self.enrichment.clone();
        Box::pin(async move {
            let loaded = postgres
                .load_anime(LoadAnimeRequest {
                    anime_id: anime_id.clone(),
                })
                .await
                .map_err(|status| map_grpc_status(&status))?
                .into_inner();

            let merged = enrichment
                .merge_anime(MergeAnimeRequest {
                    anime_id: anime_id.clone(),
                    source_pages: loaded.source_pages,
                    partial_source_pages: loaded.partial_source_pages,
                    corrections: loaded.corrections,
                    generated_texts: Vec::new(),
                    known_episodes: loaded.known_episodes,
                })
                .await
                .map_err(|status| map_grpc_status(&status))?
                .into_inner();

            let save_res = postgres
                .save_anime(SaveAnimeRequest {
                    anime_id,
                    expected_version: loaded.version,
                    anime: merged.anime,
                    merge_version,
                    relation_claims: merged.relation_claims,
                    episodes: merged.episodes,
                })
                .await;

            match save_res {
                Ok(resp) => {
                    let saved = resp.into_inner();
                    let mut changed_episode_ids = saved.created_episode_ids;
                    changed_episode_ids.extend(saved.updated_episode_ids);
                    Ok(MergeAttemptOutcome::Saved(MergeAnimeOutput {
                        has_changed: saved.has_changed,
                        changed_episode_ids,
                        has_changed_synopses: !merged.provider_synopses_hash.is_empty(),
                    }))
                }
                Err(status) if status.code() == tonic::Code::Aborted => {
                    Ok(MergeAttemptOutcome::VersionConflict(status.to_string()))
                }
                Err(status) => Err(map_grpc_status(&status)),
            }
        })
    }

    fn record_refresh(&self, input: RecordRefreshInput) -> BoxFuture<'_, Result<(), PortError>> {
        let mut postgres = self.postgres.clone();
        Box::pin(async move {
            let outcome = match input.outcome {
                RefreshOutcomeKind::Succeeded => ProtoRefreshOutcome::Succeeded as i32,
                RefreshOutcomeKind::PagesFailed => ProtoRefreshOutcome::PagesFailed as i32,
                RefreshOutcomeKind::Failed => ProtoRefreshOutcome::Failed as i32,
            };
            postgres
                .record_refresh(RecordRefreshRequest {
                    entity_type: ProtoEntityType::Anime as i32,
                    entity_id: input.anime_id,
                    outcome,
                    refresh_after: Some(prost_types::Duration {
                        seconds: input.refresh_after_days.max(1) * 86_400,
                        nanos: 0,
                    }),
                })
                .await
                .map_err(|status| map_grpc_status(&status))?;
            Ok(())
        })
    }
}

/// Top-level Temporal workflow starter using `USE_EXISTING` and inherited `RefreshTrigger`.
#[derive(Clone)]
pub struct TemporalWorkflowStarter {
    client: Client,
}

impl TemporalWorkflowStarter {
    /// Creates a starter backed by a connected Temporal `client`.
    #[must_use]
    pub fn new(client: Client) -> Self {
        Self { client }
    }
}

#[derive(Serialize)]
struct ChildRefreshStartInput {
    entity_id: String,
    trigger: String,
    priority: u32,
}

/// Encodes a serializable workflow input into a Temporal JSON [`RawValue`].
fn encode_json_raw_value<T: Serialize>(value: &T) -> Result<RawValue, PortError> {
    let bytes = serde_json::to_vec(value)
        .map_err(|err| PortError::non_retryable(format!("failed to serialize input: {err}")))?;
    let mut metadata = std::collections::HashMap::new();
    metadata.insert("encoding".to_owned(), b"json/plain".to_vec());
    Ok(RawValue {
        payloads: vec![Payload {
            metadata,
            data: bytes,
            ..Payload::default()
        }],
    })
}

impl WorkflowStarterPort for TemporalWorkflowStarter {
    fn start_entity_workflows(
        &self,
        input: StartEntityWorkflowsInput,
    ) -> BoxFuture<'_, Result<usize, PortError>> {
        let client = self.client.clone();
        Box::pin(async move {
            let mut started = 0_usize;
            let trigger_val = if input.trigger.is_empty() {
                "sweep".to_owned()
            } else {
                input.trigger.clone()
            };

            let mut priority = Priority::default();
            priority.priority_key = Some(if input.priority == 0 {
                3
            } else {
                input.priority.clamp(1, 5)
            });

            let trigger_key = SearchAttributeKey::keyword(REFRESH_TRIGGER_SEARCH_ATTRIBUTE);
            let search_attrs = SearchAttributes::new([trigger_key.value_set(trigger_val.clone())]);

            for episode_id in input.episode_ids {
                let wf_id = build_refresh_episode_workflow_id(&episode_id);
                let opts = WorkflowStartOptions::new(UPDATE_SERVICE_TASK_QUEUE, wf_id)
                    .id_conflict_policy(WorkflowIdConflictPolicy::UseExisting)
                    .priority(priority.clone())
                    .search_attributes(search_attrs.clone())
                    .build();
                let raw_input = encode_json_raw_value(&ChildRefreshStartInput {
                    entity_id: episode_id,
                    trigger: trigger_val.clone(),
                    priority: input.priority,
                })?;
                client
                    .start_workflow(
                        UntypedWorkflow::new("RefreshEpisodeWorkflow"),
                        raw_input,
                        opts,
                    )
                    .await
                    .map_err(|err| PortError::retryable(err.to_string()))?;
                started += 1;
            }

            if input.start_synopsis {
                let wf_id = build_write_synopsis_workflow_id(&input.anime_id);
                let opts = WorkflowStartOptions::new(AGENT_SERVICE_TASK_QUEUE, wf_id)
                    .id_conflict_policy(WorkflowIdConflictPolicy::UseExisting)
                    .priority(priority)
                    .search_attributes(search_attrs)
                    .build();
                let raw_input = encode_json_raw_value(&ChildRefreshStartInput {
                    entity_id: input.anime_id,
                    trigger: trigger_val,
                    priority: input.priority,
                })?;
                client
                    .start_workflow(
                        UntypedWorkflow::new("WriteSynopsisWorkflow"),
                        raw_input,
                        opts,
                    )
                    .await
                    .map_err(|err| PortError::retryable(err.to_string()))?;
                started += 1;
            }

            Ok(started)
        })
    }
}
