    /// Stores a fetched page through `StorePage`.
    ///
    /// # Errors
    ///
    /// Returns `INVALID_ARGUMENT` for a page the request does not describe correctly, or the
    /// mapped status of a database error.
    async fn store_page(
        &self,
        request: Request<StorePageRequest>,
    ) -> Result<Response<StorePageResponse>, Status> {
        let req = request.into_inner();
        self.record_message_size(req.encoded_len() as u64);

        let page = req
            .page
            .ok_or_else(|| Status::invalid_argument("page must be provided"))?;
        let observation = build_page_observation(page, &self.providers_without_review)?;

        let record_outcome = record_page_observation(&self.pool, observation)
            .await
            .map_err(|err| map_db_error(&err))?;

        Ok(Response::new(StorePageResponse {
            has_changed: record_outcome.has_changed,
        }))
    }

    /// Loads a work's merge inputs through `LoadAnime`.
    ///
    /// # Errors
    ///
    /// Returns `INVALID_ARGUMENT` for an invalid work ID, `NOT_FOUND` for a missing or deleted
    /// work, or the mapped status of a database error.
    async fn load_anime(
        &self,
        request: Request<LoadAnimeRequest>,
    ) -> Result<Response<LoadAnimeResponse>, Status> {
        let anime_id = Uuid::parse_str(&request.into_inner().anime_id)
            .map_err(|err| Status::invalid_argument(format!("invalid anime_id UUID: {err}")))?;

        let outcome = load_anime(&self.pool, anime_id)
            .await
            .map_err(|err| map_db_error(&err))?;

        let source_pages = to_proto_stored_pages(outcome.source_pages);

        let partial_source_pages = outcome
            .partial_source_pages
            .iter()
            .map(to_proto_page_key)
            .collect();

        let corrections = to_proto_corrections(outcome.corrections);
        let known_episodes = outcome
            .known_episodes
            .into_iter()
            .map(to_proto_episode_reference)
            .collect();

        let response = LoadAnimeResponse {
            version: outcome.version,
            source_pages,
            partial_source_pages,
            corrections,
            known_episodes,
        };
        self.record_message_size(response.encoded_len() as u64);

        Ok(Response::new(response))
    }

