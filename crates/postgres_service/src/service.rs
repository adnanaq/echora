/// Converts a page key into its proto message.
pub(crate) fn to_proto_page_key(key: &PageKey) -> ProtoPageKey {
    let entity_type = match key.entity_type() {
        EntityType::Anime => ProtoEntityType::Anime,
        EntityType::Episode => ProtoEntityType::Episode,
        EntityType::Character => ProtoEntityType::Character,
    };
    ProtoPageKey {
        provider: key.provider().as_str().to_owned(),
        entity_type: entity_type as i32,
        address: key.address().as_str().to_owned(),
    }
}

/// Converts a UTC timestamp into a protobuf `Timestamp`.
fn to_proto_timestamp(timestamp: DateTime<Utc>) -> prost_types::Timestamp {
    prost_types::Timestamp {
        seconds: timestamp.timestamp(),
        nanos: i32::try_from(timestamp.timestamp_subsec_nanos()).unwrap_or(0),
    }
}

/// Converts a fetched page from a `StorePage` request into a page observation.
///
/// A fetch reports what the provider answered, so the request decides the outcome this way:
/// - `is_dead` is refused, since only a reviewer's approval, or two "not found" answers a
///   day apart once the provider's review is turned off, may mark a page dead.
/// - `is_not_found` records a "not found" answer, which may not carry responses.
/// - A page with no responses records a failed fetch.
/// - A page with responses records a successful fetch.
///
/// # Errors
///
/// Returns `INVALID_ARGUMENT` when the page key, entity type or fetch time is missing or
/// invalid, when `is_dead` is set, or when a "not found" answer carries responses.
fn build_page_observation(
    page: ProtoStoredPage,
    providers_without_review: &HashSet<Provider>,
) -> Result<PageObservation, Status> {
    let ProtoStoredPage {
        page_key,
        fetched_at,
        is_dead,
        responses,
        is_not_found,
    } = page;
    if is_dead {
        return Err(Status::invalid_argument(
            "page.is_dead cannot be stored from a fetch; a dead page is confirmed by review",
        ));
    }
    let page_key = parse_page_key(
        page_key.ok_or_else(|| Status::invalid_argument("page.page_key must be provided"))?,
    )?;
    let observed_at = parse_fetch_time(
        fetched_at.ok_or_else(|| Status::invalid_argument("page.fetched_at must be provided"))?,
    )?;

    let outcome = if is_not_found {
        if !responses.is_empty() {
            return Err(Status::invalid_argument(
                "page.is_not_found cannot be combined with responses",
            ));
        }
        FetchOutcome::NotFound {
            require_review: !providers_without_review.contains(&page_key.provider()),
        }
    } else if responses.is_empty() {
        FetchOutcome::Failed
    } else {
        FetchOutcome::Success {
            responses: responses
                .into_iter()
                .map(|response| PageResponse {
                    request_name: response.request_name,
                    content_type: response.content_type,
                    body: response.body,
                })
                .collect(),
        }
    };

    Ok(PageObservation {
        page_key,
        observed_at,
        outcome,
    })
}

/// Converts a proto page key into a validated [`PageKey`].
///
/// # Errors
///
/// Returns `INVALID_ARGUMENT` for an unknown provider, an unspecified or unknown entity type,
/// or an address the provider's pattern does not allow.
fn parse_page_key(proto_key: ProtoPageKey) -> Result<PageKey, Status> {
    let provider: Provider = proto_key
        .provider
        .parse()
        .map_err(|err| map_db_error(&err))?;
    let entity_type = match ProtoEntityType::try_from(proto_key.entity_type) {
        Ok(ProtoEntityType::Anime) => EntityType::Anime,
        Ok(ProtoEntityType::Episode) => EntityType::Episode,
        Ok(ProtoEntityType::Character) => EntityType::Character,
        Ok(ProtoEntityType::Unspecified) | Err(_) => {
            return Err(Status::invalid_argument(
                "page.page_key.entity_type must be specified",
            ));
        }
    };
    PageKey::new(provider, entity_type, proto_key.address).map_err(|err| map_db_error(&err))
}

/// Converts the proto fetch time of a page into a UTC timestamp.
///
/// # Errors
///
/// Returns `INVALID_ARGUMENT` when the nanoseconds are negative or the time is out of range.
fn parse_fetch_time(fetched_at: prost_types::Timestamp) -> Result<DateTime<Utc>, Status> {
    let nanos = u32::try_from(fetched_at.nanos)
        .map_err(|_| Status::invalid_argument("page.fetched_at.nanos is invalid"))?;
    DateTime::<Utc>::from_timestamp(fetched_at.seconds, nanos)
        .ok_or_else(|| Status::invalid_argument("page.fetched_at is out of range"))
}

/// Reads which providers' missing pages are marked dead without review.
///
/// Each provider has the setting `DEAD_PAGE_REVIEW_<PROVIDER>`, such as `DEAD_PAGE_REVIEW_MAL`.
/// Review stays on unless the setting is `0`, `false` or `no`, and it is turned off for a
/// provider once reviews of its dead pages keep being confirmed. `read_setting` returns a
/// setting's value, so the caller decides where settings come from.
pub fn read_providers_without_review(
    read_setting: impl Fn(&str) -> Option<String>,
) -> HashSet<Provider> {
    Provider::ALL
        .into_iter()
        .filter(|provider| {
            let setting_name = format!(
                "DEAD_PAGE_REVIEW_{}",
                provider.as_str().to_ascii_uppercase()
            );
            read_setting(&setting_name).is_some_and(|setting_value| {
                matches!(
                    setting_value.trim().to_ascii_lowercase().as_str(),
                    "0" | "false" | "no"
                )
            })
        })
        .collect()
}

