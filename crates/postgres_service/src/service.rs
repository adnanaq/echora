/// Maximum gRPC message size (64 MiB) for RPCs carrying raw provider page bodies.
pub const MAX_PAGE_MESSAGE_BYTES: usize = 64 * 1024 * 1024;

/// Maps a `postgres_db::Error` into a `tonic::Status` in one place.
///
/// A rule violation is the caller's to fix, so it never maps to `INTERNAL`, which callers retry.
/// - A version conflict is `ABORTED`, so the merge loads, merges and saves again.
/// - A unique violation is `FAILED_PRECONDITION`, since stored rows already hold the key,
///   such as an undeleted episode with the same number.
/// - A foreign-key violation is `INVALID_ARGUMENT`, since the request names a value the
///   lookup tables do not have.
#[must_use]
pub fn map_db_error(err: &postgres_db::Error) -> Status {
    if err.is_version_conflict() {
        Status::aborted(err.to_string())
    } else if err.is_not_found() {
        Status::not_found(err.to_string())
    } else if err.is_invalid_argument() || err.is_foreign_key_violation() {
        Status::invalid_argument(err.to_string())
    } else if err.is_unique_violation() {
        Status::failed_precondition(err.to_string())
    } else {
        Status::internal(err.to_string())
    }
}

/// Implements `PostgresService` gRPC RPCs backed by `postgres_db`.
#[derive(Debug)]
pub struct PostgresGrpcService {
    pool: PgPool,
    providers_without_review: HashSet<Provider>,
    max_message_bytes_seen: AtomicU64,
    max_message_gauge: Gauge<u64>,
}

impl PostgresGrpcService {
    /// Creates a service backed by `pool`.
    ///
    /// Missing pages of `providers_without_review` are marked dead without review, once two
    /// "not found" answers a day apart reach the threshold.
    #[must_use]
    pub fn new(pool: PgPool, providers_without_review: HashSet<Provider>) -> Self {
        let meter = global::meter("postgres-service");
        let max_message_gauge = meter
            .u64_gauge("postgres_service.grpc.max_message_bytes")
            .with_description("Largest encoded gRPC message carrying page bodies, in bytes")
            .build();
        Self {
            pool,
            providers_without_review,
            max_message_bytes_seen: AtomicU64::new(0),
            max_message_gauge,
        }
    }

    /// Records the largest message size this service has handled as a metric.
    fn record_message_size(&self, bytes: u64) {
        let prev = self
            .max_message_bytes_seen
            .fetch_max(bytes, Ordering::Relaxed);
        let max_seen = prev.max(bytes);
        self.max_message_gauge.record(max_seen, &[]);
    }
}

